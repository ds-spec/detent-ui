  tags?: Tag[]
  /** The demo fills its stage edge to edge instead of being fitted. */
  bleed?: boolean
  /** Takes two columns in the grid. */
  wide?: boolean
  /** Scale on the detail page. */
  zoom?: number
  /** What makes it, for the detail page. */
  details: string[]
